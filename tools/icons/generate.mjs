import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';

const revision = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7';
const upstream = `https://raw.githubusercontent.com/google/material-design-icons/${revision}/`;
const prototype = await readFile(new URL('../../docs/mobile-app-ui.html', import.meta.url), 'utf8');
const loaded = prototype.match(/icon_names=([a-z_,]+)/)?.[1]?.split(',');
if (!loaded) throw new Error('Material Symbols list missing from the prototype');

const used = [...prototype.matchAll(/\bI\('([a-z_]+)'/g)].map((match) => match[1]);
const names = [...new Set([...loaded, ...used])].sort();
const filled = ['format_list_bulleted', 'location_on', 'settings', 'today'];

async function download(path) {
  const response = await globalThis.fetch(new URL(path, upstream), { signal: globalThis.AbortSignal.timeout(15_000) });
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.text();
}

async function symbol(name, fill) {
  const source = await download(`symbols/web/${name}/materialsymbolsrounded/${name}${fill ? '_fill1' : ''}_24px.svg`);
  const viewBox = source.match(/viewBox="([0-9.\s-]+)"/)?.[1];
  const paths = [...source.matchAll(/<path\b[^>]*\bd="([^"<>]+)"/g)].map((match) => match[1]);
  if (!viewBox || !paths.length || /<(circle|rect|polyline|polygon|g|use)\b/.test(source)) {
    throw new Error(`${name}: expected SVG path data`);
  }
  return { viewBox, paths };
}

async function library(names, filled) {
  const entries = [];
  for (let index = 0; index < names.length; index += 6) {
    const batch = await Promise.all(names.slice(index, index + 6).map(async (name) => [name, await symbol(name, filled)]));
    entries.push(...batch);
  }
  return Object.fromEntries(entries);
}

const [outline, fills, license] = await Promise.all([library(names, false), library(filled, true), download('LICENSE')]);
const output = new URL('../../apps/mobile/src/icons/', import.meta.url);
await mkdir(output, { recursive: true });
const source = [
  '// Generated by tools/icons/generate.mjs.',
  '// Material Symbols Rounded by Google LLC, Apache-2.0.',
  `// Upstream: https://github.com/google/material-design-icons/tree/${revision}/symbols/web`,
  '',
  `export const symbols = ${JSON.stringify(outline, null, 2)} as const;`,
  '',
  `export const filledSymbols = ${JSON.stringify(fills, null, 2)} as const;`,
  '',
].join('\n');
await Promise.all([
  writeFile(new URL('symbols.generated.ts', output), source),
  writeFile(new URL('LICENSE.material-symbols', import.meta.url), `${license.trimEnd()}\n`),
]);
