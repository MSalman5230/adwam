import { writeFileSync } from 'node:fs';

const firstYear = 1400;
const lastYear = 1500;
const dayMs = 86_400_000;
const formatter = new Intl.DateTimeFormat('en', {
  calendar: 'islamic-umalqura',
  numberingSystem: 'latn',
  timeZone: 'UTC',
  year: 'numeric',
  month: 'numeric',
  day: 'numeric',
});

const starts: number[] = [];
for (
  let time = Date.UTC(1979, 0, 1);
  time < Date.UTC(2081, 0, 1);
  time += dayMs
) {
  const parts = Object.fromEntries(
    formatter
      .formatToParts(new Date(time))
      .map(({ type, value }) => [type, Number(value)]),
  );
  const year = parts.year ?? 0;
  if (year < firstYear || parts.day !== 1) continue;
  starts.push(time);
  if (year === lastYear + 1 && parts.month === 1) break;
}

const first = starts[0];
if (
  first === undefined ||
  starts.length !== (lastYear - firstYear + 1) * 12 + 1
) {
  throw new Error('Node did not supply all Umm al-Qura months');
}
const months = starts
  .slice(1)
  .map((time, index) => {
    const earlier = starts[index];
    const length = earlier === undefined ? 0 : (time - earlier) / dayMs;
    if (length !== 29 && length !== 30)
      throw new Error('Invalid Umm al-Qura month length');
    return length === 30 ? '1' : '0';
  })
  .join('');
const years = months.match(/.{12}/g) ?? [];
const data = [
  '// Generated by scripts/gen-umalqura.ts using Node Intl.',
  'export const UMM_AL_QURA_FIRST_YEAR = ' + firstYear + ';',
  "export const UMM_AL_QURA_FIRST_DATE = '" +
    new Date(first).toISOString().slice(0, 10) +
    "' as const;",
  '',
  '// One year per row, with 0 for a 29-day month and 1 for a 30-day month.',
  'export const UMM_AL_QURA_MONTHS = [',
  ...years.map((year) => "  '" + year + "',"),
  "].join('');",
  '',
].join('\n');
writeFileSync(
  new URL('../packages/core/src/umalqura-data.ts', import.meta.url),
  data,
);
